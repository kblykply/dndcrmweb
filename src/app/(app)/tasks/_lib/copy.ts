export function errorText(error: unknown, copy: Copy) {
  let message = error instanceof Error ? error.message : copy.error;
  try {
    const data = JSON.parse(message);
    const code = data.code;
    if (["WORK_VERSION_CONFLICT", "WRITE_CONFLICT"].includes(code))
      return copy.stale;
    if (code === "DATABASE_BUSY") return copy.busy;
    if (code === "WORK_UNFINISHED") return copy.doneChecklist;
    if (code === "WORK_CLOSE_FIRST") return copy.archiveCloseFirst;
    if (data.statusCode === 403 || data.statusCode === 404)
      return copy.noPermission;
    message = Array.isArray(data.message)
      ? data.message.join(" · ")
      : data.message || copy.error;
  } catch {
    /* Plain-text errors are also supported by the existing API. */
  }
  return message;
}
