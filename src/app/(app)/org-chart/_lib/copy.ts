export function errorText(error: unknown, copy: Copy) {
  const text = error instanceof Error ? error.message : copy.error;
  try {
    const parsed = JSON.parse(text) as { code?: keyof Copy["errors"]; message?: string | string[] };
    if (parsed.code && copy.errors[parsed.code]) return copy.errors[parsed.code];
    return Array.isArray(parsed.message) ? parsed.message.join(" · ") : parsed.message || text;
  } catch { return text; }
}
